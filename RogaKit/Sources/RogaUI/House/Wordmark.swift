/// The word roga in the brand's rounded lowercase letters, from
/// docs/design/branding/roga-wordmark.svg, for the first screen of setup. The
/// bowls of its letters are holes, so it fills with the even-odd rule.
struct Wordmark: View {
    /// How wide to draw it. Its height follows.
    var width: CGFloat = 132
    var color = Color.primary

    var body: some View {
        let scale = width / WordmarkOutline.size.width
        WordmarkOutline.letters
            .applying(CGAffineTransform(scaleX: scale, y: scale))
            .fill(color, style: FillStyle(eoFill: true))
            .frame(width: width, height: WordmarkOutline.size.height * scale)
            .accessibilityElement()
            .accessibilityLabel("Roga")
            .accessibilityAddTraits(.isImage)
    }
}

